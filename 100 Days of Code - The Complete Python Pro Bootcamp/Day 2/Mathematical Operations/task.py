# This line of code outputs 3.0 but if we remove the brackets around 3 + 3 it will output 7.0 this proves
# that Python uses PEMDAS and to prioritize any operation we have to put it in brackets.
print(3 * (3 + 3) / 3 - 3)

# Full form of PEMDAS
# P = Parentheses
# E = Exponents
# M = Multiplication
# D = Division
# A = Addition
# S = Subtraction

# NOTE: Multiplication has the same value as Division and any one can be prioritized.
